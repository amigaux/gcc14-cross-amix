#!/bin/bash
# make-cxx-wrappers.sh -- give AMIX's C headers the C++ linkage guards they
# were written eight years too early to have.
#
# AMIX is SVR4.0 from 1991.  Its headers contain no
#     #ifdef __cplusplus
#     extern "C" {
# so every declaration they make gets C++ linkage when a C++ translation unit
# includes them, and the program then fails to link against libc:
#     undefined reference to `_Z6printfPKcz'
#
# That is not a corner case.  It is every C header, for every C++ file -- and it
# is not only OUR code: libstdc++'s own sources compile against these headers,
# so without this its objects reference a mangled abort() and free() and nothing
# links at all.  That is why the wrappers go into GCC's include-fixed, which
# every compilation sees, rather than onto a command line we control.
#
# Each wrapper is guarded on __cplusplus, so the same file serves C unchanged.
#
# There are three cases in that directory, and getting the third one wrong is
# what makes libstdc++ fail to link with a mangled abort() and free():
#
#   1. Headers we repaired ourselves.  They carry their own guard: skip.
#   2. Headers GCC's own fixincludes already copied and edited -- stdio.h,
#      stdlib.h, string.h, unistd.h, sys/types.h and about twenty more.  Those
#      copies SHADOW the sysroot, so a #include_next wrapper would never be
#      reached, and fixincludes does not add linkage guards.  They are wrapped
#      IN PLACE, keeping whatever fixincludes did to them.
#   3. Everything else: a small wrapper that reaches the real header.
#
# Regenerated rather than committed: the set of headers depends on the AMIX
# installation, and a hand-written list would quietly miss one.
#
# Usage: make-cxx-wrappers.sh <sysroot> <include-fixed dir>
set -e
SRC="$1/usr/include"
OUT="$2"
[ -d "$SRC" ] || { echo "make-cxx-wrappers.sh: no $SRC" >&2; exit 1; }
[ -n "$OUT" ] || { echo "make-cxx-wrappers.sh: no output directory given" >&2; exit 1; }
mkdir -p "$OUT"

count=0 skipped=0 wrapped=0
while IFS= read -r rel; do
	if [ -e "$OUT/$rel" ]; then
		# Case 1 or 2.  The test is whether the header already declares C
		# linkage -- NOT whether it merely mentions __cplusplus.  AMIX's
		# stdlib.h says "#ifndef __cplusplus" for wchar_t and nothing else,
		# and a weaker test skips it: the symptom is libstdc++ failing to
		# link against a mangled free() and abort() while every other header
		# behaves.
		if grep -q 'extern "C"' "$OUT/$rel"; then
			skipped=$((skipped + 1)); continue
		fi
		wrapped=$((wrapped + 1))
		{
			echo "/* Linkage guard added by toolchain/make-cxx-wrappers.sh."
			echo " * The body below is GCC fixincludes' own copy of AMIX's <$rel>,"
			echo " * kept as it is; only the guard AMIX predates is added. */"
			echo "#ifdef __cplusplus"
			echo "extern \"C\" {"
			echo "#endif"
			cat "$OUT/$rel"
			echo "#ifdef __cplusplus"
			echo "}"
			echo "#endif"
		} > "$OUT/$rel.tmp"
		mv "$OUT/$rel.tmp" "$OUT/$rel"
		continue
	fi
	mkdir -p "$OUT/$(dirname "$rel")"
	guard="AMIX_CXX_WRAP_$(echo "$rel" | tr 'a-z./-' 'A-Z___')"
	{
		echo "/* Generated by toolchain/make-cxx-wrappers.sh -- do not edit."
		echo " * AMIX's <$rel> predates C++ and declares no linkage, so it is"
		echo " * reached from here with the guard it lacks. */"
		echo "#ifndef $guard"
		echo "#define $guard"
		echo "#ifdef __cplusplus"
		echo "extern \"C\" {"
		echo "#endif"
		echo "#include_next <$rel>"
		echo "#ifdef __cplusplus"
		echo "}"
		echo "#endif"
		echo "#endif"
	} > "$OUT/$rel"
	count=$((count + 1))
done < <(cd "$SRC" && find . -name '*.h' -type f -not -path './X11/*' -not -path './Xol/*' -printf '%P\n' | sort)

echo "make-cxx-wrappers.sh: $count wrappers, $wrapped fixincludes copies guarded, $skipped already guarded"
