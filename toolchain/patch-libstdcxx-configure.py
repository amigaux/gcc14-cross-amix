#!/usr/bin/env python3
"""Teach libstdc++'s configure what the AMIX C library actually has.

libstdc++'s crossconfig.m4 ends in a case that rejects anything it does not
recognise -- "No support for this host/target combination." -- and m68k-elf is
not on its list, so the build stops before it starts.

An EMPTY case gets past that but is not enough for a hosted build. libstdc++
then believes the target has no float math functions and compiles its own
fallbacks in src/c++98/math_stubs_float.cc, each guarded by _GLIBCXX_HAVE_<F>.
AMIX declares eighteen of those functions in <math.h>, so the fallbacks collide
with the real ones:

    math_stubs_float.cc:35:3: error: conflicting declaration of
                              'float fabsf(float)' with 'C' linkage

So the case this inserts declares what the target really has, derived from the
target's own <math.h> rather than from a list someone typed. The long double
variants are deliberately left undeclared: SVR4.0 predates C99 and has none, so
libstdc++ SHOULD build its fallbacks for those.

This edits the GENERATED configure rather than crossconfig.m4, because
regenerating that requires the exact autoconf the GCC release was made with.
Idempotent.

Usage: patch-libstdcxx-configure.py <libstdc++-v3/configure> <amix sysroot>
"""
import os
import re
import sys

configure, sysroot = sys.argv[1], sys.argv[2]

mathh = os.path.join(sysroot, "usr/include/math.h")
stubs = os.path.join(os.path.dirname(configure), "src/c++98/math_stubs_float.cc")
for f in (mathh, stubs):
    if not os.path.exists(f):
        sys.exit("patch-libstdcxx-configure.py: missing %s" % f)

# What libstdc++ is prepared to substitute for, and what the target already has.
wanted = re.findall(r"#ifndef _GLIBCXX_(HAVE_[A-Z0-9_]+)", open(stubs).read())
declared = open(mathh, errors="replace").read()
have = [m for m in wanted
        if re.search(r"\b%s\s*\(" % m[len("HAVE_"):].lower(), declared)]

if not have:
    sys.exit("patch-libstdcxx-configure.py: found no float math functions in %s -- "
             "check that the sysroot is the right one" % mathh)

lines = ["  m68k-*-elf*)",
         "    # AMIX (SVR4.0).  Its <math.h> declares these; without saying so,",
         "    # libstdc++ compiles its own fallbacks and they collide with the real",
         "    # declarations.  The long double variants are absent and left absent.",
         "    # Generated by toolchain/patch-libstdcxx-configure.py."]
lines += ['    $as_echo "#define %s 1" >>confdefs.h' % m for m in have]
lines += ["    ;;", ""]
case = "\n".join(lines) + "\n"

MARKER = ('  *)\n'
          '    as_fn_error $? "No support for this host/target combination."')

text = open(configure).read()
text = re.sub(r"  m68k-\*-elf\*\)\n(?:.*\n)*?    ;;\n\n", "", text, count=1)

if MARKER not in text:
    sys.exit("patch-libstdcxx-configure.py: target case list does not look as "
             "expected; check crossconfig.m4 in this GCC release")

open(configure, "w").write(text.replace(MARKER, case + MARKER, 1))
print("libstdc++ configure: m68k-*-elf* case with %d math functions (%s...)"
      % (len(have), ", ".join(m[len("HAVE_"):].lower() for m in have[:4])))
